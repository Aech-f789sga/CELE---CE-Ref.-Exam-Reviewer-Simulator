/** Booklet folio span for an item's working, e.g. `{ page: 371, pageEnd: 372 }`. */
export function mstcNov2016SolutionPages(
  item: number,
): { page: number; pageEnd: number } | null {
  const p = SOLUTION_PAGES[`i${String(item).padStart(2, '0')}`];
  if (!p) return null;
  return { page: p[0], pageEnd: p[p.length - 1] };
}

/**
 * The cropped booklet working for one item. Throws rather than falling back to
 * a neighbouring item, so a missing crop is loud instead of wrong.
 */
export function mstcNov2016SolutionImages(item: number): string[] {
  const key = `i${String(item).padStart(2, '0')}`;
  const images = SOLUTION_CROPS[key];
  if (!images) throw new Error(`No MSTC Nov 2016 solution crop for item ${item}`);
  return images;
}

/** True when the booklet prints worked working for this item. */
export function mstcNov2016HasSolutionCrop(item: number): boolean {
  return Boolean(SOLUTION_CROPS[`i${String(item).padStart(2, '0')}`]);
}
