/** Booklet crops for one item's worked solution, or undefined if none. */
export function mstcMay2022SolutionImages(item: number): string[] | undefined {
  return SOLUTION_CROPS[`i${String(item).padStart(2, '0')}`];
}

/** Whether the booklet prints a worked solution for this item. */
export function mstcMay2022HasSolutionCrop(item: number): boolean {
  return Boolean(SOLUTION_CROPS[`i${String(item).padStart(2, '0')}`]);
}

/** Booklet folio the item's working starts on. */
export function mstcMay2022SolutionPage(item: number): number {
  return SOLUTION_PAGES[item];
}

/** Booklet folio the item's working ends on. */
export function mstcMay2022SolutionPageEnd(item: number): number {
  return SOLUTION_PAGE_END[item] ?? SOLUTION_PAGES[item];
}

/** Figure crops keyed by the name used in the question data. */
export const MSTC_MAY_2022_FIGURES: Record<string, string> = {
  fig_q30_traverse: figQ30Traverse,
  fig_q33_table4: figQ33Table4,
  fig_q33_table5: figQ33Table5,
};

export function mstcMay2022Figure(key: string, alt: string): string {
  const src = MSTC_MAY_2022_FIGURES[key];
  if (!src) throw new Error(`No MSTC May 2022 figure for "${key}"`);
  return `<div class="flex flex-col items-center justify-center w-full py-2">
  <img
    src="${src}"
    alt="${alt}"
    class="max-w-xl w-full h-auto object-contain rounded-lg bg-white p-2.5 shadow-sm border border-slate-200"
    loading="eager"
    referrerpolicy="no-referrer"
  />
</div>`;
}

/**
 * Two or more figure crops stacked in one wrapper.
 *
 * Item 33 prints two tables, and concatenating two single-figure blocks puts
 * them side by side in the figure panel, which halves each one's width and
 * clips the right-hand column of the second table. One flex-column wrapper
 * keeps them full width and stacked.
 */
export function mstcMay2022FigureStack(
  figures: { key: string; alt: string }[],
): string {
  const imgs = figures
    .map(({ key, alt }) => {
      const src = MSTC_MAY_2022_FIGURES[key];
      if (!src) throw new Error(`No MSTC May 2022 figure for "${key}"`);
      return `<img
    src="${src}"
    alt="${alt}"
    class="max-w-xl w-full h-auto object-contain rounded-lg bg-white p-2.5 shadow-sm border border-slate-200"
    loading="eager"
    referrerpolicy="no-referrer"
  />`;
    })
    .join('');
  return `<div class="flex flex-col items-center justify-center gap-3 w-full py-2">${imgs}</div>`;
}
