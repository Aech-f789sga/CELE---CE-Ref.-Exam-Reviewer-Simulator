/**
 * Strength of Materials — items 1–227, transcribed from the printed set.
 *
 * Source: Margallo's Buckling Review Center, "[STRENGTH OF MATERIALS]"
 * practice problems, 27 landscape pages, two columns, 80 numbered
 * "Situation N" blocks, numbered straight through 1–227 and ending with a
 * printed "--- END ---" on page 27. Same series as the Basic Math, Calculus,
 * Statics, Fluid Mechanics and Physics banks, so it lives beside them and is
 * drawn by the same "By topics" machinery.
 *
 * ## Key status
 *
 * **No answer key has been supplied for this booklet.** Every item is
 * therefore `keyPending` and nothing here is scored: the drill reports the
 * sitting as unscoreable rather than marking every answer wrong. The
 * arithmetic that keeps a pending item out of a score, a pass mark and the
 * leaderboard lives in `grading.ts`; `keyPending` is the only switch, and it
 * is set here once per item by the factory below.
 *
 * When the key arrives it is encoded as a letters-only array in this module,
 * the way `FLUID_KEY` and `STAT_KEY` already are, and the `keyPending` flag
 * comes off the topic definitions in `topicBanks.ts`. Nothing else changes.
 *
 * ## Sections
 *
 *   SIMPLE STRESSES - AXIAL, SHEAR, AND BEARING STRESS    1–48   str-simple
 *   AXIAL DEFORMATION                                    49–58   str-deform
 *   TORSION                                              59–76   str-torsion
 *   SHEAR AND MOMENT                                     77–104  str-shear-moment
 *   FLEXURAL STRESS AND TRANSVERSE SHEAR STRESS         105–149  str-flexural
 *   COMBINED LOADINGS                                   150–199  str-combined
 *   THIN-WALLED PRESSURE VESSEL                         200–209  str-vessel
 *   MOHR'S CIRCLE                                       210–227  str-mohr
 *
 * The eight headings are the booklet's own, and they are what the drill
 * offers as topics: a learner who wants torsion should not have to sit
 * shear-and-moment diagrams to get it.
 *
 * Two of them are filed where the booklet files them rather than where the
 * subject matter would suggest: Situations 78 and 79 read like pressure-
 * vessel problems but ask for principal stresses, so they sit under Mohr's
 * Circle.
 *
 * ## Situations
 *
 * Items stay contiguous by situation and repeat the shared wording at the
 * head of `text`, as the Statics and Fluid banks do, so a paired item is
 * never shown without the data it needs. `situationText` carries the same
 * wording for callers that want it separately.
 *
 * ## Figures
 *
 * Most situations carry a drawing, and most of those drawings carry data the
 * prose does not repeat — a span, an eccentricity, a cross-section, an angle
 * on a failure plane. Each is reproduced as a panel cut from the scanned page
 * and stored at `public/images/strength/sit-<n>.jpg`; the item's `figureSvg`
 * points at it.
 *
 * The panel is the whole printed block, heading to first item, not a
 * tightly-trimmed drawing. Trimming was tried and abandoned: in a two-column
 * scan the drawing's own dimension labels sit a few pixels clear of its body,
 * and every rule that isolated the body either clipped a label or swallowed
 * the item stem below it. A panel repeats a few lines of the situation's
 * prose, which is already shown as text — that repetition is the price of
 * never shipping a half-drawing.
 *
 * Seven situations have no panel. Situations 6 and 7 straddle a page break,
 * so their drawing and their data land on different pages; 37 and 54 are
 * headed by prose whose drawing sits outside the block, leaving a panel that
 * would be text only; and 77, 78 and 79 are headed by lines the page
 * segmentation did not see. Their items are still answerable — the prose and
 * the printed `Given:` lists carry the numbers — and they render without a
 * figure rather than with a misleading one.
 *
 * ## Board area
 *
 * Every topic is filed under PSAD. Strength of materials is not one of the
 * three board areas on its own, and inventing a fourth would ripple through
 * `SUBJECT_CONFIGS` and every lookup keyed on it; the booklet's own footer
 * groups these problems under "PRINCIPLE OF STRUCTURAL DESIGN AND ANALYSIS",
 * which is the PSAD grouping. As with the other banks, the real
 * classification is `topicId`/`category` and `subject` is only carried to
 * satisfy the type.
 *
 * ## Transcription notes
 *
 * Text is as printed, including the booklet's own slips; nothing was silently
 * corrected, because an option that quietly disagrees with the page is worse
 * than one that looks odd. Where an item looked wrong it was re-read off the
 * page at 2× rather than guessed at, and the following are the page's own:
 *
 *   Items 26, 31  ask for an area in mm², which is the printed unit.
 *   Item 48       nests a second `Given:` list inside the item, after the
 *                 stem; kept where it is printed rather than moved up.
 *   Item 60       asks for torsional rigidity in "×10⁹ N-mm²". The exponent
 *                 is the printed one and checks out against G·J.
 *   Item 94       offers "1766" where its neighbours carry one decimal.
 *   Items 129–131 give "Length L = 150 mm" against spans drawn as 2L + L in
 *                 metres; transcribed as printed.
 *   Item 209      sets its options in two columns; they are stored in printed
 *                 order a, b, c, d rather than column-major.
 *   Items 222–227 print a stray mark inside the option letter ("ad", "d&",
 *                 "W", "Ca"); the letter was read off the page and the value
 *                 kept.
 *
 * Missing spaces are the booklet's, not the OCR's — but where the OCR dropped
 * a space the page does have ("Ifthe" for "If the"), the space was restored,
 * because that is transcription rather than editing.
 */
import type { TopicQuestion } from './topicBanks';

/**
 * A panel cut from the scanned page for a situation that carries a drawing.
 *
 * `figureSvg` is injected with `dangerouslySetInnerHTML`, so it must be HTML
 * rather than a bare path — handing it a URL renders the path as text.
 *
 * `max-w-2xl` rather than a fixed width: these panels are wide and short, and
 * a panel scaled to a phone width would shrink its dimension labels below
 * reading size. `w-auto h-auto` keeps the aspect ratio.
 */
function strPanel(situation: number, caption: string): string {
  const file = String(situation).padStart(2, '0');
  return `<div class="flex flex-col items-center justify-center w-full py-2">
  <img
    src="/images/strength/sit-${file}.jpg"
    alt="Strength of Materials — ${caption}"
    class="max-w-2xl w-auto h-auto object-contain rounded-lg bg-white p-2 shadow-sm border border-slate-200"
    loading="lazy"
  />
</div>`;
}

function makeStrItem(topicId: string, category: string) {
  return (
    number: number,
    text: string,
    opts: [string, string, string, string],
    page: number,
    situation: number,
    situationText: string,
    figure: boolean
  ): TopicQuestion => ({
    id: `str-${String(number).padStart(3, '0')}`,
    number,
    pageNumber: page,
    subject: 'PSAD',
    year: 0,
    month: 'May',
    category,
    text: situationText ? `${situationText}\n\n${text}` : text,
    figureSvg: figure ? strPanel(situation, `Situation ${situation}`) : undefined,
    figureCaption: figure ? `Situation ${situation}` : undefined,
    options: opts.map((t, i) => ({ label: 'ABCD'[i] as 'A', text: t })),
    /*
     * Placeholder only. `keyPending` below is what stops this letter from
     * ever being compared against a learner's answer, so it is deliberately
     * not a guess at the right one.
     */
    correctAnswer: 'A',
    keyPending: true,
    topicId,
    situation,
    situationText: situationText || undefined,
    solution: {
      summary: 'No printed key supplied for this booklet yet.',
      steps: [],
      finalAnswer: '',
      note: 'Answer key pending — this item is not scored.',
    },
  });
}

