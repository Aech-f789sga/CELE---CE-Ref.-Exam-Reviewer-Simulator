/**
 * Scanned assets for Gillesania Volume 4, MSTC (Mathematics, Surveying &
 * Transportation Engineering) May 2015.
 *
 * Source: Diego Inocencio T. Gillesania, "Civil Engineering Reference Vol. 4",
 * Mathematics, Surveying & Transportation Engineering section of the May 2015
 * PRC board examination. The section is key-then-solutions: questions on folios
 * 1-10, the printed answer key at the foot of folio 11, and "Solutions to May
 * 2015 Examination" opening on folio 12 and closing on folio 37.
 *
 * ## How the crops were cut
 *
 * The booklet marks every worked item with a small open-book glyph and the item
 * number in the blank left margin. Each crop opens on that marker and closes on
 * the last inked row before the next one, so a block is never cut through a line
 * of working. The markers were found by template-matching the glyph rather than
 * by any fixed column threshold: the scan's x-offset drifts by up to 180 px
 * between pages, so a column rule picks up body text on some pages and misses
 * the margin on others. A dozen glyphs are too faint to match (the photocopy
 * thins them out) and were read off a ruled margin band by eye.
 *
 * Where a block runs over a page turn the working is cropped in two parts, `a`
 * and `b`, shown in reading order — items 23, 29, 41, 54 and 70.
 *
 * On a page where a block opens at the very top, the running head and its rule
 * sit only a few pixels above the marker; those are painted out rather than
 * cropped away, so no book title, date banner or folio leaks into an image.
 *
 * Item 1's crop also carries the "Situation 1 (1 to 3)" label the booklet prints
 * above it.
 *
 * Images are imported statically so Vite emits them into dist/assets and they
 * survive a production build.
 */

