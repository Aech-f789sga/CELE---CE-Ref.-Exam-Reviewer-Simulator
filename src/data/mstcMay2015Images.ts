export function mstcMay2015SolutionImages(item: number): string[] {
  const crops = CROPS[item];
  if (!crops) throw new Error(`No MSTC May 2015 solution crop for item ${item}`);
  return crops;
}

export function mstcMay2015HasSolutionCrop(item: number): boolean {
  return (CROPS[item]?.length ?? 0) > 0;
}
