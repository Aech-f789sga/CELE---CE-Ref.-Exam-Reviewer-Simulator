/**
 * Wraps the statement drawings for a situation in the markup
 * `EngineeringFigure` expects.
 *
 * `figureSvg` is injected with `dangerouslySetInnerHTML`, so it must be HTML,
 * not a bare URL — handing it a URL renders the path as text.
 */
export function besaMar2026MstcFigure(key: string): string | undefined {
  const srcs = FIGURES[key];
  if (!srcs?.length) return undefined;
  const imgs = srcs
    .map(
      (src, i) => `<img
    src="${src}"
    alt="Besavilla MSTC March 2026 illustration${srcs.length > 1 ? ` ${i + 1}` : ''}"
    class="max-w-md w-full h-auto object-contain rounded-lg bg-white p-2.5 shadow-sm border border-slate-200"
    loading="eager"
    referrerpolicy="no-referrer"
  />`,
    )
    .join('\n  ');
  return `<div class="flex flex-col items-center justify-center gap-2 w-full py-2">
  ${imgs}
</div>`;
}

/**
 * Scanned working for a situation. `SolutionFigures` puts these straight into
 * `<img src>`, so here a bare URL is what it wants.
 */
export function besaMar2026MstcSolutionImages(key: string): string[] {
  return SOLUTIONS[key] ?? [];
}
