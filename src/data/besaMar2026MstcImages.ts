/**
 * Scanned assets for BESAVILLA MSTC March 2026.
 *
 * Source: Venancio I. Besavilla Jr., "Civil Engineering Licensure Examinations
 * — Mathematics and Surveying, March 2026" (34 PDF pages, booklet pages M-280
 * to M-310; the PDF prints M-282 four times over, so 31 pages are distinct).
 *
 * 73 numbered situations. Twenty-two are four-choice items whose key is marked
 * by italicising the option and setting a pointing hand beside it; the other
 * fifty-one print a worked "Solution:" block, so those items carry
 * `workedSolution: true`, no choices, and are answered by revealing the scanned
 * working and self-marking.
 *
 * - Solutions: one crop per column of the working, in reading order. This
 *   booklet alternates between one-column pages (a long derivation printed
 *   across the sheet) and two-column pages, and a situation often runs from the
 *   left column of one page into the right column of the next, so a situation
 *   can need three crops.
 * - Figures: nineteen statements print a drawing. Four of the multiple-choice
 *   items (the pancake-collapse sketches, the two integral forms, the four cost
 *   curves, the four Venn diagrams) print their options as drawings, so those
 *   crops cover the whole option block and the letters sit inside the image.
 *
 * Images are imported statically so Vite emits them into dist/assets and they
 * survive a Vercel build.
 */

