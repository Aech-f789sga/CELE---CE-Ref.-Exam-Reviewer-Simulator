/**
 * Wraps a figure crop in the markup `EngineeringFigure` expects.
 *
 * `figureSvg` is injected with `dangerouslySetInnerHTML`, so it must be HTML,
 * not a bare URL — handing it a URL string renders the path as text.
 */
function fluidFigure(key: string, caption: string): string {
  return `<div class="flex flex-col items-center justify-center w-full py-2">
  <img
    src="/images/fluid/${key}.png"
    alt="Fluid Mechanics figure — ${caption}"
    class="max-w-md w-full h-auto object-contain rounded-lg bg-white p-2.5 shadow-sm border border-slate-200"
    loading="eager"
  />
</div>`;
}

interface ItemExtra {
  /** Crop name under `public/images/fluid/`, without the extension. */
  figure?: string;
  /** Caption for the crop; defaults to the item number. */
  caption?: string;
  /** Printed "Situation N" this item belongs to. */
  situation?: number;
}

function makeFluidItem(topicId: string, category: string) {
  return (
    number: number,
    text: string,
    opts: [string, string, string, string],
    page: number,
    extra: ItemExtra = {}
  ): TopicQuestion => {
    const situation = extra.situation;
    const shared = situation === undefined ? '' : SITUATIONS[situation];
    return {
      id: `fluid-${String(number).padStart(3, '0')}`,
      number,
      pageNumber: page,
      subject: 'MSTC',
      year: 0,
      month: 'May',
      category,
      text: shared ? `${shared}\n\n${text}` : text,
      figureSvg: extra.figure
        ? fluidFigure(extra.figure, extra.caption ?? `Item ${number}`)
        : undefined,
      figureCaption: extra.caption ?? (extra.figure ? `Item ${number}` : undefined),
      options: opts.map((t, i) => ({ label: 'ABCD'[i] as 'A', text: t })),
      correctAnswer: 'A',
      keyPending: true,
      topicId,
      situation,
      situationText: shared || undefined,
      solution: {
        summary: 'No printed key supplied for this booklet yet.',
        steps: [],
        finalAnswer: '',
        note: 'Answer key pending — this item is not scored.',
      },
    };
  };
}

